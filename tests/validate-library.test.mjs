test('buildIndex falls back to the filename stem and empty summary when frontmatter is absent', () => {
  const root = makeRepo({ 'library/finance/orphan.md': '# no frontmatter\n' });

  const index = buildIndex(root);

  assert.match(index, /- \[orphan\]\(\.\.\/library\/finance\/orphan\.md\) — /);
  assert.equal(index.includes('undefined'), false);
});

// --- C2: the shared parser region stays byte-identical across the two validators ---

// The two validators deliberately do not share a module (each ships into a repo
// with no daftplate). This asserts the shared region stays byte-identical, so a
// one-sided bug fix fails here rather than in someone else's CI. A genuine
// divergence is allowed — delete this test and say why in the same commit.
const SHARED_START = '// Frontmatter contract, deliberately narrow';
const SHARED_END = '  return { values, structured };\n}';

const region = (url) => {
  const src = readFileSync(new URL(url, import.meta.url), 'utf8');
  const from = src.indexOf(SHARED_START);
  const to = src.indexOf(SHARED_END, from);
  assert.ok(from !== -1 && to !== -1, `shared region markers not found in ${url}`);
  return src.slice(from, to + SHARED_END.length);
};

test('both validators carry a byte-identical frontmatter parser', () => {
  assert.equal(
    region('../profiles/content-library/files/scripts/validate-library.mjs'),
    region('../profiles/design-vault/files/scripts/validate-vault.mjs'),
  );
});

// --- C3: the validator runs where it lands, and a fresh library is not clean
//     until its first index is generated ---

test('validate-library.mjs exits 1 with index-missing on a freshly scaffolded repo', () => {
  const dest = emptyDir();
  scaffold(ROOT, 'content-library', dest, values('dry-lib'));

  const result = spawnSync(process.execPath, [join(dest, 'scripts', 'validate-library.mjs'), dest], { encoding: 'utf8' });

  assert.equal(result.status, 1, `expected 1, got ${result.status}: ${result.stdout}`);
  assert.match(result.stderr, /index-missing/);
});

test('validate-library.mjs exits 0 after --write-index on a scaffolded repo', () => {
  const dest = emptyDir();
  scaffold(ROOT, 'content-library', dest, values('dry-lib'));

  const result = spawnSync(
    process.execPath,
    [join(dest, 'scripts', 'validate-library.mjs'), dest, '--write-index'],
    { encoding: 'utf8' },
  );

  assert.equal(result.status, 0, `exited ${result.status}: ${result.stderr}`);
});

// --- Task 3c.4: the validator must ship without daftplate ---

test('validate-library.mjs imports only node: builtins, because it ships without daftplate', () => {
  const source = readFileSync(
    new URL('../profiles/content-library/files/scripts/validate-library.mjs', import.meta.url),
    'utf8',
  );
  const specifiers = [...source.matchAll(/^import\s[^'"]*['"]([^'"]+)['"]/gm)].map((m) => m[1]);

  assert.ok(specifiers.length > 0, 'no imports found — did the file move?');
  const foreign = specifiers.filter((s) => !s.startsWith('node:'));
  assert.deepEqual(foreign, [], `these would not resolve in a scaffolded library: ${foreign.join(', ')}`);
});
